# --- Cache ---
# Uses Redis when REDIS_URL is set (e.g. docker-compose); otherwise falls back
# to an in-process locmem cache so local SQLite dev still works with zero config.
REDIS_URL = os.environ.get('REDIS_URL')
if REDIS_URL:
    CACHES = {
        'default': {
            'BACKEND': 'django_redis.cache.RedisCache',
            'LOCATION': REDIS_URL,
            'KEY_PREFIX': 'kanban',
            'OPTIONS': {
                'CLIENT_CLASS': 'django_redis.client.DefaultClient',
            },
        },
    }
else:
    CACHES = {
        'default': {
            'BACKEND': 'django.core.cache.backends.locmem.LocMemCache',
        },
    }

# --- Channels (WebSocket) ---
# Uses the Redis channel layer when REDIS_URL is set; otherwise falls back to an
# in-process layer so local SQLite dev (single process) still works out of the box.
